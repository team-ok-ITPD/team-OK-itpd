"""Write a learner's VS Code workspace folder for one bug."""

import json
import keyword
import re
from pathlib import Path

from django.conf import settings

from .models import Draft, IdeToken
from .views import LiteralError, _json_safe

# The debug configuration learners already use in the exercise workspace.
LAUNCH_JSON = settings.BASE_DIR.parent.parent / "exercise" / ".vscode" / "launch.json"
# The Debug GYM venv in the VS Code image; the system python3 there has no pytest.
VENV_PYTHON = "/opt/debug-gym/bin/python"


class WorkspaceError(ValueError):
    pass


def workspace_dir(user, bug):
    return Path(settings.WORKSPACES_DIR) / str(user.id) / bug.slug


def _identifier(name, what):
    if not name.isidentifier() or keyword.iskeyword(name):
        raise WorkspaceError(f"The bug's {what} {name!r} is not a valid Python name.")
    return name


def _test_name(name, used):
    base = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "case"
    base = f"test_{base}"
    candidate, number = base, 2
    while candidate in used:
        candidate, number = f"{base}_{number}", number + 1
    used.add(candidate)
    return candidate


def render_tests(bug):
    """Return a pytest file with one test function per stored test."""
    module = _identifier(Path(bug.file_name).stem, "file name")
    function = _identifier(bug.function_name, "function name")
    lines = [
        f'"""Reproduction tests for {module}.py, generated by Debug GYM."""',
        "",
        f"from {module} import {function}",
    ]
    used = set()
    for test in bug.tests:
        try:
            # Same checks as an edited test: only plain JSON-like values reach the file.
            given, expected = _json_safe(test["input"]), _json_safe(test["expected"])
        except (KeyError, TypeError, LiteralError) as error:
            raise WorkspaceError(f"A stored test of {bug.slug} is not valid: {error}") from error
        lines += [
            "",
            "",
            f"def {_test_name(str(test.get('name', '')), used)}() -> None:",
            f"    assert {function}({given!r}) == {expected!r}",
        ]
    return "\n".join(lines) + "\n"


def write_workspace(user, bug):
    """Write the bug's code, tests and debug configuration; return the folder."""
    if not re.fullmatch(r"[A-Za-z_]\w*\.py", bug.file_name or ""):
        raise WorkspaceError(f"The bug's file name {bug.file_name!r} is not a plain Python file name.")
    tests = render_tests(bug)
    draft = Draft.objects.filter(user=user, bug=bug).first()
    code = draft.code if draft is not None else bug.buggy_code

    folder = workspace_dir(user, bug)
    (folder / "tests").mkdir(parents=True, exist_ok=True)
    (folder / ".vscode").mkdir(exist_ok=True)
    (folder / bug.file_name).write_text(code if code.endswith("\n") else code + "\n")
    (folder / "tests" / f"test_{bug.slug.replace('-', '_')}.py").write_text(tests)
    write_vscode_config(folder)
    write_extension_config(user, bug, folder)
    return folder


def write_vscode_config(folder):
    """Copy the exercise's debug configuration and point VS Code at the Debug GYM venv."""
    launch = json.loads(LAUNCH_JSON.read_text())
    for configuration in launch["configurations"]:
        configuration["python"] = VENV_PYTHON
    (folder / ".vscode" / "launch.json").write_text(json.dumps(launch, indent=2) + "\n")
    workspace_settings = {"python.defaultInterpreterPath": VENV_PYTHON}
    (folder / ".vscode" / "settings.json").write_text(json.dumps(workspace_settings, indent=2) + "\n")


def write_extension_config(user, bug, folder):
    """Tell the Debug GYM extension where and as whom to submit; replaces any older token."""
    config = {
        "server": settings.DEBUG_GYM_IDE_SERVER_URL,
        "site": f"{settings.DEBUG_GYM_SITE_URL}/#/practice/{bug.slug}",
        "bug": bug.slug,
        "file": bug.file_name,
        "token": IdeToken.issue(user, bug),
    }
    config_dir = folder / ".debug-gym"
    config_dir.mkdir(exist_ok=True)
    path = config_dir / "config.json"
    path.write_text(json.dumps(config, indent=2) + "\n")
    path.chmod(0o600)
